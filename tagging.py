PRESS_RELEASE_TYPE = "Пресс-релиз"

# Тип, заданный самой площадкой. Есть источники, где материал пишет не
# редакция, а сама компания: companies.rbc.ru — это витрина, куда компании
# выкладывают свои пресс-релизы. По тексту такой материал от новости не
# отличить, а знать это важно: «Сервисная служба FLAMAX провела работы» —
# сообщение компании о себе, а не новость рынка.
#
# Сигнал при этом не подавляется: пресс-релиз о назначении гендиректора —
# настоящее кадровое событие.
SOURCE_MATERIAL_TYPES: Dict[str, str] = {
    "rbc_companies": PRESS_RELEASE_TYPE,
}


# Признак типа ищется только в начале материала — в заголовке и первых фразах
# лида. Дальше по тексту слова вроде «тренинг», «практикум» или «конференция»
# встречаются как упоминания, а не как описание жанра: аналитика «79%
# уволившихся назвали причиной ухода...» становилась «Обучением» лишь потому,
# что в середине текста упомянут Яндекс Практикум, — и теряла кадровый сигнал.
TYPE_SCAN_LIMIT = 180


def detect_material_type(text: str, source: str | None = None) -> str:
    """
    Тип материала: реклама, мероприятие, обучение, исследование, вакансия,
    мнение — или «Новость», если ни один признак не сработал.

    Признаки в тексте важнее площадки: рекламный пост остаётся рекламой, даже
    если опубликован там, где по умолчанию лежат пресс-релизы.
    """
    head = (text or "").lower()[:TYPE_SCAN_LIMIT]
    for material_type, markers in MATERIAL_MARKERS.items():
        if any(_MATERIAL_PATTERNS[marker].search(head) for marker in markers):
            return material_type

    return SOURCE_MATERIAL_TYPES.get(source or "", NEWS_TYPE)


