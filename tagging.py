# Насколько далеко от маркера ищется объект сокращения.
OBJECT_WINDOW = 50
# Окно влево шире окна вправо: между предметом и глаголом помещается
# определение и обстоятельство — «медианная зарплата стоматолога за год
# сократилась».
SUBJECT_WINDOW = 45

# Окончание слова после основы маркера: по нему видно возвратную форму.
_WORD_TAIL = re.compile(r"^[а-яё]*")


def _is_reflexive(text_lower: str, end: int) -> bool:
    """
    Возвратная ли форма глагола: «сократилась», «сокращается».

    Она означает, что предмет уменьшился сам, и назван он слева от глагола
    («зарплата сократилась»), а не справа. У переходной формы («компания
    сократит штат») объект стоит справа.
    """
    tail = _WORD_TAIL.match(text_lower[end:]).group(0)
    return tail.endswith(("ся", "сь"))


def _has_excluded_object(text_lower: str, marker: str, end: int) -> bool:
    """Сокращают не человека, а что-то другое: день, зарплату, издержки."""
    words = MARKER_EXCLUSIONS.get(marker, ())
    if not words:
        return False

    if _is_reflexive(text_lower, end):
        # «Медианная зарплата за год сократилась» — предмет слева. Смотрим
        # только вплотную к глаголу: дальше начинается посторонний текст.
        head = text_lower[max(0, end - SUBJECT_WINDOW):end]
        return any(word in head for word in words)

    tail = text_lower[end:end + OBJECT_WINDOW]
    return any(word in tail for word in words)


def _has_context(text_lower: str, marker: str, start: int, end: int) -> bool:
    """Есть ли рядом с вхождением слово, подтверждающее неоднозначный маркер."""
    words = TAG_CONTEXT.get(marker, ())
    if not words:
        return False

    window = text_lower[max(0, start - CONTEXT_WINDOW):end + CONTEXT_WINDOW]
    return any(word in window for word in words)


def _marker_hits(text_lower: str, marker: str) -> bool:
    """Сработал ли маркер с учётом его неоднозначности."""
    matches = [
        m for m in _MARKER_PATTERNS[marker].finditer(text_lower)
        if not _has_excluded_object(text_lower, marker, m.end())
    ]
    if marker not in AMBIGUOUS_MARKERS:
        return bool(matches)

    return any(
        _has_context(text_lower, marker, match.start(), match.end())
        for match in matches
    )


def detect_tags(text: str) -> List[str]:
    """
    Тематические теги новости, в порядке объявления в TAG_MARKERS.

    Пустой список означает, что тема не распознана, — это нормальный результат,
    и он честнее, чем присвоение тега «Прочее» наугад.
    """
    if not text:
        return []

    text_lower = text.lower()
    return [
        tag
        for tag, markers in TAG_MARKERS.items()
        if any(_marker_hits(text_lower, marker) for marker in markers)
    ]


def hr_signal(tags: Sequence[str], material_type: str = NEWS_TYPE) -> HrSignal:
    """
    Оценка влияния материала на кадровые движения.

    Возвращается сильнейшее сработавшее правило: у новости про сокращения на
    фоне убытков сигнал высокий, а не средний.

    Реклама, анонсы и учебные программы сигнала не получают, даже когда
    кадровая лексика в них есть: вебинар «как проводить сокращения» — это
    приглашение на вебинар, а не сокращение.
    """
    if material_type in NON_EVENT_TYPES:
        return HrSignal("нет", f"{material_type}: не сообщает о кадровом событии")

    for tag, level, reason in HR_RULES:
        if tag in tags:
            return HrSignal(level, f"{tag}: {reason}")
    return NO_SIGNAL


class Analysis(NamedTuple):
    """Полный разбор материала: тип, темы и кадровый сигнал."""

    material_type: str
    tags: List[str]
    signal: HrSignal


def analyze_text(text: str, source: str | None = None) -> Analysis:
    """Тип материала, темы и HR-сигнал за один разбор текста."""
    material_type = detect_material_type(text, source)
    tags = detect_tags(text)
    return Analysis(material_type, tags, hr_signal(tags, material_type))


# Теги, по которым новость считается кадровой. Из их маркеров собирается фильтр
# для широких федеральных лент: без него в базу попадали бы сводки с фронта и
# спортивные результаты, а нужны кадровые движения.
HR_TOPIC_TAGS = ("Назначения", "Сокращения", "Найм и рост")

HR_TOPIC_PATTERN = re.compile(
    "|".join(
        sorted(
            (re.escape(marker) for tag in HR_TOPIC_TAGS for marker in TAG_MARKERS[tag]),
            key=len,
            reverse=True,
        )
    )
)

# Одной кадровой лексики для отбора мало: «назначение пенальти» и «возглавил
# клуб» — тоже назначения. Поэтому нужен ещё и деловой контекст...
BUSINESS_CONTEXT = (
    "компан", "банк", "холдинг", "корпорац", "бизнес", "рынок", "завод",
    "предприят", "ритейл", "ретейл", "оператор", "гендиректор", "директор",
    "совет директоров", "топ-менеджер", "вице-президент", "ооо", "пао", "ао ",
    "гк ", "группа", "сотрудник", "штат", "персонал", "работник", "ит-",
    "стартап", "маркетплейс", "разработчик", "вендор", "офис",
)

# ...и отсечение тем, где кадровая лексика значит совсем другое.
NON_BUSINESS_NOISE = (
    # спорт
    "пенальти", "матч", "сборн", "чемпионат", "тренер", "клуб", "турнир",
    "олимп", "футбол", "хоккей",
    # война
    "бпла", "беспилотник", "фронт", "всу", "боевик",
    # государственная политика: назначение министра — не корпоративное
    # кадровое движение, а таких новостей в федеральных лентах много
    "депутат", "выбор", "правительств", "министр", "губернатор", "мэр ",
    "президент", "парламент", "зеленск",
)


def is_hr_business_news(text: str) -> bool:
    """
    Годится ли новость широкой ленты для кадровой аналитики.

    Требуется кадровая лексика И деловой контекст, а спортивные и военные
    сюжеты отсекаются: в федеральных лентах их на порядок больше, и без этого
    фильтра «назначение пенальти» попадало бы в отчёт как кадровое движение.
    """
    if not text:
        return False

    lowered = text.lower()
    if any(word in lowered for word in NON_BUSINESS_NOISE):
        return False
    if not HR_TOPIC_PATTERN.search(lowered):
        return False
    return any(word in lowered for word in BUSINESS_CONTEXT)
