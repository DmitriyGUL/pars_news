def _marker_pattern(marker: str) -> str:
    """
    Шаблон маркера.

    Маркер — основа слова, поэтому граница слова ставится только слева: «сокращ»
    должно находиться в «сокращения». Маркеры, заканчивающиеся пробелом
    ("суд "), проверяются как есть — пробел и есть правая граница.
    """
    return r"\b" + re.escape(marker)


